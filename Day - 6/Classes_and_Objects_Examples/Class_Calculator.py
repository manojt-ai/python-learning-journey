class calculator:

    def add(self,a,b):
        print("a + b = ",a + b)

    def sub(self,a,b):
        print("a + b = ",a - b)

    def mul(self,a,b): 
        print("a + b = ",a * b)

    def div(self,a,b):
        print("a + b = ",a / b)

Num = calculator()

Num.add(3,5)
Num.sub(9,5)
Num.mul(6,45)
Num.div(650,5)





  
