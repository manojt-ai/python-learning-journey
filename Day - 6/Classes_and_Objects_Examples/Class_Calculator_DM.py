class calculator:

    def __init__(self,num1,num2):
        self.a = num1
        self.b = num2

    def add(self):
        print("a + b = ",self.a + self.b)

    def sub(self):
        print("a + b = ",self.a - self.b)

    def mul(self): 
        print("a + b = ",self.a * self.b)

    def div(self):
        print("a + b = ",self.a / self.b)

Num = calculator(5,5)

Num.add()
Num.sub()
Num.mul()
Num.div()





  
